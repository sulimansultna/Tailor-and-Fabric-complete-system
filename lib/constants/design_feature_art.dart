String designFeatureSvg(String key) {
  final paths = designFeatureStrokes(key).map((stroke) {
    final points = stroke.map((point) => '${point.$1},${point.$2}').join(' ');
    return '<polyline points="$points"/>';
  }).join();
  return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 80 60">'
      '<g fill="none" stroke="#000000" stroke-width="1.6" '
      'stroke-linecap="round" stroke-linejoin="round">$paths</g></svg>';
}
